"""Final comparison on the test window (2011-09-01..2011-11-30) with the tuned parameters.

Every model is refit on all data before 2011-09-01. Writes the RECSYS section of
docs/RESULTS.md, artifacts/test_results.json, and logs each run to MLflow.
"""

from __future__ import annotations

import json
import logging

import mlflow
import numpy as np
import pandas as pd

from shopsage.config import ARTIFACTS_DIR, MLFLOW_URI, SEED, TEST_START
from shopsage.eval.metrics import ndcg_at_k
from shopsage.eval.runner import PROTOCOLS, evaluate_model
from shopsage.eval.split import ground_truth, make_test_split
from shopsage.recsys.base import Recommender
from shopsage.recsys.data import Interactions, load_transactions
from shopsage.recsys.train import SEARCH_SPACE, K, mlflow_key
from shopsage.reporting import md_table, write_section

log = logging.getLogger(__name__)
ORDER = ["popularity", "recent_popularity", "buy_again", "item_knn", "als"]
COLUMNS = [
    "model",
    "precision",
    "recall",
    "ndcg",
    "map",
    "hit_rate",
    "coverage",
    "diversity",
    "pop_bias",
    "ndcg 95% CI",
    "val ndcg",
]


def bootstrap_ci(values: np.ndarray, n: int = 1000, seed: int = SEED) -> tuple[float, float]:
    """95% percentile bootstrap interval of the mean over users."""
    rng = np.random.default_rng(seed)
    means = values[rng.integers(0, len(values), size=(n, len(values)))].mean(axis=1)
    lo, hi = np.percentile(means, [2.5, 97.5])
    return float(lo), float(hi)


def per_user_ndcg(model: Recommender, data: Interactions, holdout: pd.DataFrame, protocol: str):
    truth = ground_truth(holdout, data, new_items_only=protocol == "new")
    recs = model.recommend_ids(list(truth), k=K, exclude_seen=protocol == "new")
    return np.array([ndcg_at_k(recs.get(u, []), truth[u], K) for u in truth if truth[u]])


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    best = json.loads((ARTIFACTS_DIR / "best_params.json").read_text())
    tx = load_transactions()
    train, test = make_test_split(tx)
    data = Interactions.from_lines(train, end=pd.Timestamp(TEST_START))
    mlflow.set_tracking_uri(MLFLOW_URI)
    mlflow.set_experiment("shopsage-recsys-test")

    results: dict[str, list[dict]] = {}
    for protocol in PROTOCOLS:
        rows = []
        for name in ORDER:
            params = best[protocol][name]["params"]
            model = SEARCH_SPACE[name][0](**params).fit(data)
            res = evaluate_model(model, data, test, k=K, protocol=protocol)
            lo, hi = bootstrap_ci(per_user_ndcg(model, data, test, protocol))
            with mlflow.start_run(run_name=f"{name}-{protocol}-test"):
                mlflow.set_tags({"model": name, "protocol": protocol, "split": "test"})
                mlflow.log_params(params)
                mlflow.log_metrics({mlflow_key(k): v for k, v in res.items()})
            row = {"model": name, "params": params, **{k.split("@")[0]: v for k, v in res.items()}}
            row["ndcg 95% CI"] = f"{lo:.4f}–{hi:.4f}"
            row["ndcg_ci"] = [lo, hi]
            row["val ndcg"] = float(best[protocol][name]["val"][f"ndcg@{K}"])
            rows.append(row)
            log.info("[%s] %s ndcg=%.4f [%.4f, %.4f]", protocol, name, res[f"ndcg@{K}"], lo, hi)
        results[protocol] = rows

    (ARTIFACTS_DIR / "test_results.json").write_text(json.dumps(results, indent=2))
    n_all = int(results["all"][0]["n_users"])
    n_new = int(results["new"][0]["n_users"])
    params_lines = "\n".join(
        f"- `{r['model']}`: all = `{best['all'][r['model']]['params']}`, "
        f"new = `{best['new'][r['model']]['params']}`"
        for r in results["all"]
    )
    md = f"""
All metrics @{K}, test window 2011-09-01 to 2011-11-30, models refit on everything before
2011-09-01 with the parameters chosen on validation (NDCG@{K}). Generated by
`python -m shopsage.recsys.evaluate`. CI = 95% bootstrap interval over users (1,000 resamples).
`val ndcg` = NDCG@{K} of the same configuration on the validation window (Jun–Aug 2011).

**Protocol `all`** — any item bought in the window counts ({n_all:,} warm customers).

{md_table(results["all"], COLUMNS)}

**Protocol `new`** — only items the customer never bought before; bought items are excluded
from the lists ({n_new:,} customers with at least one new item).

{md_table(results["new"], COLUMNS)}

Chosen parameters:
{params_lines}
"""
    write_section("RECSYS", md)


if __name__ == "__main__":
    main()
