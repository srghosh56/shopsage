"""Write the KEY-RESULTS block of README.md and docs/MODEL_CARD.md from saved artifacts.

Run after `make eval train agent-eval`: `uv run python scripts/update_docs.py`.
"""

from __future__ import annotations

import json

import pandas as pd

from shopsage.config import ARTIFACTS_DIR, DOCS_DIR, ROOT
from shopsage.llm.agreement import parse
from shopsage.llm.judge import LABELS_CSV
from shopsage.reporting import md_table, write_section


def pct(v: float) -> str:
    return f"{v:.0%}"


def main() -> None:
    rec = json.loads((ARTIFACTS_DIR / "test_results.json").read_text())
    clv = json.loads((ARTIFACTS_DIR / "clv_validation.json").read_text())
    agent_path = ARTIFACTS_DIR / "agent_eval.json"
    agent = json.loads(agent_path.read_text())["summary"] if agent_path.exists() else None

    rows = []
    for name in ["popularity", "recent_popularity", "buy_again", "item_knn", "als"]:
        a = next(r for r in rec["all"] if r["model"] == name)
        n = next(r for r in rec["new"] if r["model"] == name)
        rows.append(
            {
                "model": name,
                "NDCG@10 (all)": f"{a['ndcg']:.3f}",
                "HitRate@10 (all)": f"{a['hit_rate']:.3f}",
                "NDCG@10 (new items)": f"{n['ndcg']:.3f}",
                "HitRate@10 (new items)": f"{n['hit_rate']:.3f}",
                "coverage (new)": f"{n['coverage']:.3f}",
            }
        )
    o, r = clv["orders"], clv["revenue"]
    md = f"""
**Recommenders** — test window 2011-09-01..2011-11-30, {int(rec["all"][0]["n_users"]):,} warm
customers (`all`) / {int(rec["new"][0]["n_users"]):,} (`new` = only never-bought items):

{md_table(rows, list(rows[0]))}

**CLV** (6-month holdout, {clv["customers"]:,} customers): BG/NBD purchases MAE
{o["bgnbd"]["MAE"]:.2f} vs naive {o["naive"]["MAE"]:.2f}, total purchases error
{o["bgnbd"]["total_error_pct"]:+.1f}%; revenue total error {r["bgnbd_gg"]["total_error_pct"]:+.1f}%
(naive {r["naive"]["total_error_pct"]:+.1f}%); predicted top 20% earned
{r["top20_share_bgnbd_gg"]:.1%} of holdout revenue.
"""
    if agent:
        w, n = agent["with_tools"], agent["no_tools"]
        md += f"""
**Assistant** (40 questions, local LLM): correct in-scope answers {pct(w["correct_in_scope"])}
with tools vs {pct(n["correct_in_scope"])} without; right tool {pct(w["tool_choice"])};
out-of-scope refused {pct(w["oos_refused"])} (no tools: {pct(n["oos_refused"])}).
"""
    labels = pd.read_csv(LABELS_CSV, dtype=str, keep_default_na=False)
    human = labels.my_label.map(parse).dropna()
    if len(human):
        missed = labels.loc[human.index][human.eq(0)].check.eq("passed").sum()
        md += f"""
**Explanations** ({len(human)} labelled by one human): {int(human.sum())} faithful; the rule check
let through {missed} of the {int((human == 0).sum())} unfaithful ones. See RESULTS section 4.
"""
    md += "\nFull tables and caveats: [docs/RESULTS.md](docs/RESULTS.md). Generated by `scripts/update_docs.py`."
    write_section("KEY-RESULTS", md, ROOT / "README.md")
    write_section(
        "KEY-RESULTS", md.replace("(docs/RESULTS.md)", "(RESULTS.md)"), DOCS_DIR / "MODEL_CARD.md"
    )


if __name__ == "__main__":
    main()
